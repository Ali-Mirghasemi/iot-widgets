import { readFileSync } from 'node:fs';
import { strict as assert } from 'node:assert';
import ts from 'typescript';
const source = readFileSync(new URL('../src/library/adaptive.ts', import.meta.url), 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { isCanvasWidget, getWidgetMinimumSize, getWidgetGridMinimum, widgetSizeForGrid, resolveWidgetView, historyValues } = await import('data:text/javascript,' + encodeURIComponent(output));
const metric = {visual:'metric',category:'metrics',minSize:'1x1',supportedSizes:['1x1','2x1','2x2','3x2','3x3'],defaultSize:'1x1'};
const map = {visual:'map',category:'location',minSize:'2x2',supportedSizes:['2x2','3x2','3x3'],defaultSize:'2x2'};
const graph = {visual:'line',category:'charts',minSize:'2x2',supportedSizes:['2x2','3x2','3x3'],defaultSize:'2x2'};
assert.equal(isCanvasWidget(metric),false);
assert.equal(isCanvasWidget(map),true);
assert.equal(isCanvasWidget(graph),true);
assert.deepEqual(getWidgetMinimumSize(map),{w:2,h:2});
assert.deepEqual(getWidgetGridMinimum(map,12),{w:4,h:2});
assert.deepEqual(getWidgetGridMinimum(graph,6),{w:2,h:2});
assert.deepEqual(getWidgetGridMinimum(metric,12),{w:1,h:1});
assert.ok(graph.supportedSizes.includes(widgetSizeForGrid(graph,4,2)));
assert.equal(resolveWidgetView('1x1'), 'compact');
assert.equal(resolveWidgetView('2x1'), 'standard');
assert.equal(resolveWidgetView('3x2',{width:420,height:300}), 'detailed');
assert.equal(resolveWidgetView('3x2',{width:140,height:140}), 'compact');
assert.equal(resolveWidgetView('3x2',{width:140,height:140},'detailed'), 'compact', 'manual view cannot force overflow');
assert.equal(resolveWidgetView('1x1',{width:1200,height:800},'auto',true), 'detailed', 'expanded view has more space');
assert.equal(historyValues({value:24}), undefined, 'a single reading must never generate fake history');
assert.deepEqual(historyValues({history:[{value:12,at:1},{value:15,at:2}]}),[12,15]);
console.log('Adaptive widget tests passed: canvas minima, density, resize constraints, history.');
